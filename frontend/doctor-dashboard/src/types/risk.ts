export type RiskLevel = "LOW" | "MODERATE" | "HIGH" | "CRITICAL";

export interface RiskFactor {
  name: string;
  category: "hemodynamic" | "lifestyle" | "biomarker" | "history" | "ecg";
  impact: "low" | "medium" | "high" | "critical";
  description: string;
  value?: string | number;
}

export interface RiskAssessment {
  id: string;
  patientId: string;
  overallScore: number; // 0 to 100
  riskLevel: RiskLevel;
  tenYearCvdRiskPercentage: number; // Framingham / ASCVD derived
  primaryFactors: RiskFactor[];
  aiGenerated: boolean; // Must always be true when generated by AI
  modelVersion: string;
  generatedAt: string;
  clinicianReviewed: boolean;
  reviewedBy?: string;
  reviewedAt?: string;
  reviewNotes?: string;
  recommendations: string[];
}

export interface RiskTrendPoint {
  date: string;
  score: number;
  riskLevel: RiskLevel;
  reviewed: boolean;
}
